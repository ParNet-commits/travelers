/**
 * Records a REAL live run of the Riya preset into replay/runs/riya.ts (used by replay mode and offline fallback).
 * Never hand-edit the output. Re-record after any change to contracts, prompts or the Udaipur data.
 * Usage: npm run record:golden   (needs NEBIUS_API_KEY and TAVILY_API_KEY in .env.local; costs about $0.02-0.10)
 */
import { writeFileSync } from "node:fs";
import { GoldenRun, SSEEvent } from "../types/travelverse.js";
import { riyaPreset } from "../replay/presets.js";
import { getConfig } from "../server/config.js";
import { createDeps } from "../server/deps.js";
import { runPlan } from "../server/orchestrator/runPlan.js";
import { newRunId } from "../server/sse/sse.js";
import type { Emit } from "../server/agents/common.js";

try {
  process.loadEnvFile(".env.local");
} catch {
  /* env may come from the shell */
}
const cfg = getConfig();
if (!cfg.nebiusApiKey) {
  console.error("NEBIUS_API_KEY missing - a golden run must be a real live run.");
  process.exit(1);
}

const trip = riyaPreset();
const runId = newRunId();
const events: SSEEvent[] = [];
let seq = 0;
const t0 = Date.now();
const emit: Emit = (input) => {
  const ev = SSEEvent.parse({ ...input, seq: seq++, t: Date.now() - t0, runId });
  events.push(ev);
  const detail = ev.type === "thinking" ? ev.text.slice(0, 90) : ev.type === "rule_check" ? `${ev.outcome.ruleId} ${ev.outcome.status}` : ev.type === "llm_call" ? `${ev.agent} ${ev.model} ${ev.ok ? "ok" : "FAIL"} ${ev.ms}ms` : "";
  console.log(`${String(ev.t).padStart(6)}ms  ${ev.type.padEnd(18)} ${detail}`);
};

const result = await runPlan({ runId, request: trip, routes: cfg.models, bailOnLlmFatal: false }, createDeps(cfg), emit, new AbortController().signal);
const u = result.usage;
emit({ type: "usage", llmCalls: u.llmCalls, toolCalls: u.toolCalls, tokensIn: u.tokensIn, tokensOut: u.tokensOut, estUsd: u.estUsd, tavilyCredits: u.tavilyCredits, elapsedMs: u.elapsedMs });
emit({ type: "done", status: result.status });

if (result.status === "failed" || result.status === "cancelled") {
  console.error(`\nRun ${result.status}; NOT saved. Fix the cause (see events above) and record again.`);
  process.exit(1);
}
const llmFailures = events.filter((e) => e.type === "llm_call" && !e.ok).length;
if (result.final?.generatedBy.deterministicFallback || llmFailures > 0) {
  console.warn(`\nWARNING: ${llmFailures} model call(s) failed during this run. A hero recording should show the models working - consider re-recording.`);
}
if (result.rounds === 0) {
  console.warn("\nWARNING: the first plan passed every rule, so there is no self-correction to show. Re-record (or check the Udaipur data: the premium stay should exceed the budget and the palace should be not_step_free).");
}

const run = GoldenRun.parse({ id: "riya", recordedAt: new Date().toISOString(), request: trip, models: cfg.models, events });
const file = `/**
 * GOLDEN RUN - recorded ${run.recordedAt} from a real live run (${result.status}, ${result.rounds} re-plan(s), est. $${u.estUsd}).
 * Models: ${Object.values(cfg.models).join(", ")}
 * Generated by scripts/record-golden.ts. DO NOT EDIT BY HAND - re-record instead.
 */
import type { GoldenRun } from "../../types/travelverse.js";

export const RIYA_RUN: GoldenRun | null = ${JSON.stringify(run, null, 1)};
`;
writeFileSync("replay/runs/riya.ts", file);
console.log(`\nSaved replay/runs/riya.ts: ${events.length} events, ${(file.length / 1024).toFixed(0)} KB, status ${result.status}, rounds ${result.rounds}, $${u.estUsd}.`);
